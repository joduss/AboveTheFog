import assert from 'node:assert/strict';
import {Capacity, readExact} from '../src/terrain/transfer.ts';

const gate = new Capacity(4);
const signal = new AbortController().signal;
const release = await gate.acquire(3, signal);
const cancelled = new AbortController();
const pending = gate.acquire(2, cancelled.signal);
cancelled.abort();
await assert.rejects(pending, {name: 'AbortError'});
const next = gate.acquire(2, signal);
assert.equal(gate.used, 3);
release();
(await next)();
assert.equal(gate.used, 0);
assert.equal(gate.peak, 3);
await assert.rejects(gate.acquire(5, signal));
const stream = bytes => new Blob([new Uint8Array(bytes)]).stream();
assert.deepEqual([...new Uint8Array(await readExact(stream([1,2]), 2))], [1,2]);
await assert.rejects(readExact(stream([1]), 2), /Incomplete/);
await assert.rejects(readExact(stream([1,2,3]), 2), /Oversized/);

const {PacketStore} = await import('../src/terrain/packetStore.ts');
const packets = new PacketStore(8);
let finish;
const held = new Promise(resolve => {finish = resolve;});
let calls = 0;
const fetchPacket = async () => {calls++; return new ArrayBuffer(6);};
const a = packets.read('a',6,signal,fetchPacket,() => held);
const shared = packets.read('a',6,signal,fetchPacket,async b => b.byteLength);
assert.equal(await shared,6);
assert.equal(calls,1);
packets.clear();
const b = packets.read('b',6,signal,fetchPacket,async b => b.byteLength);
assert.equal(packets.used,6);
finish();
await a;
assert.equal(await b,6);
assert.equal(calls,2);
assert.equal(packets.peak,6);
packets.clear();
assert.equal(packets.used,0);
